export type CollaboratorStatus = "Ativo" | "Afastado" | "Desligado";

export interface Collaborator {
  id: string;
  name: string;
  role: string;
  area: string;
  /** Estabelecimento/unidade ao qual o colaborador está vinculado. */
  establishment?: string;
  cpf: string;
  matricula: string;
  rg: string;
  pis: string;
  ctps: string;
  admissionDate: string;
  /**
   * Data da última atualização do cadastro (DD/MM/AAAA), vinda de
   * `company_collaborators.updated_at`. É o que a ficha de verificação exibe.
   */
  updatedAt?: string;
  birthDate: string;
  phone: string;
  email: string;
  city: string;
  status: CollaboratorStatus;
  /** Id do colaborador designado como gestor/líder responsável. */
  managerId?: string;
  /**
   * Responsável Técnico de Segurança do Trabalho da empresa. Quando marcado,
   * o colaborador assina eletronicamente as atas da CIPA e demais documentos
   * que exigem a responsabilidade técnica.
   */
  technicalResponsible?: boolean;
  /** Alergias declaradas pelo colaborador (medicamentos, alimentos, agentes químicos...). */
  allergies?: string[];
  photo: string;
  documentsOk: number;
  documentsTotal: number;
  trainingsActive: number;
  trainingsExpired: number;
  episInUse: number;
}

